# sweep_perf.ps1 - frame time / stutter sweep over tracks and race modes, one Azahar run per combination.
#
#   powershell -ExecutionPolicy Bypass -File scripts\3ds\sweep_perf.ps1 -Tracks '0,5,8,11' -Modes 'standard,dm' -Windows 2
#
# For each (track, mode) it writes a scenario (autopilot on, quickrace track T, N windows of 1500 frames),
# runs az_run.ps1 -Perf and collects the [perf] lines into logs\az_runs\sweep_<stamp>\summary.md:
# avg / p99 / max frame time, stutter frames, the three biggest phases and the cause of the worst frame.
# Track bytes: 0..8 = TR1..TR9, 9..17 = the same driven backwards. 18 (TR0) is NOT raceable: the engine aborts
# ("Problems with [TR0.BPA] TR0-FLIP.PAL file") and the run times out.
param(
    [string]$Tracks = '0,5,8,11',          # comma separated (an array does not survive "powershell -File")
    [string]$Modes = 'standard,dm',
    [int]$Windows = 2,
    [int]$Extras = 18
)
$ErrorActionPreference = 'Stop'
$repo  = Split-Path (Split-Path $PSScriptRoot)
$stamp = Get-Date -Format 'yyyyMMdd_HHmmss'
$out   = "$repo\logs\az_runs\sweep_$stamp"
New-Item -ItemType Directory -Force $out | Out-Null
$rows = @()
$trackList = $Tracks -split ',' | ForEach-Object { [int]$_ }
$modeList  = $Modes -split ','

foreach ($mode in $modeList) {
    foreach ($track in $trackList) {
        $name = "${mode}_t$track"
        $scn  = "$out\$name.txt"
        $lines = @(
            "# generated by sweep_perf.ps1: $name",
            'until ready spam Return every 150 timeout 40000',
            'autopilot on',
            "quickrace track $track",
            'until event race_start spam Return every 150 timeout 30000',
            'until race_frames 150 timeout 20000')
        for ($i = 1; $i -le $Windows; $i++) {
            $lines += 'perf start'
            $lines += "until race_frames $(150 + 1500 * $i) timeout 150000"
            $lines += "perf report w$i"
        }
        $lines += 'quit'
        Set-Content -Path $scn -Value $lines -Encoding ascii

        "== $name"
        $log = "$out\$name.out"
        & powershell -NoProfile -ExecutionPolicy Bypass -File "$PSScriptRoot\az_run.ps1" -Scenario $scn -Perf -Mode $mode -Extras $Extras `
            -TimeoutSec (60 + 40 * $Windows) -Label "sweep_${stamp}_$name" *> $log
        $perf = Select-String -Path $log -Pattern '^\[perf\]' | ForEach-Object { $_.Line }
        foreach ($w in 1..$Windows) {
            $head  = $perf | Where-Object { $_ -match "^\[perf\] w${w}: \d+ frames, avg" } | Select-Object -First 1
            $stut  = $perf | Where-Object { $_ -match "^\[perf\] w${w}: \d+ stutter frame" } | Select-Object -First 1
            $phase = $perf | Where-Object { $_ -match "^\[perf\] w${w}: ms/frame" } | Select-Object -First 1
            $worst = $perf | Where-Object { $_ -match "^\[perf\] w${w}: worst #1" } | Select-Object -First 1
            if (-not $head) { $rows += "| $name | w$w | (no data - run failed? see $name.out) | | | | |"; continue }
            $avg = [regex]::Match($head, 'avg ([\d.]+) ms \(([\d.]+) fps\)').Groups
            $p99 = [regex]::Match($head, 'p99 ([\d.]+)').Groups[1].Value
            $max = [regex]::Match($head, 'max ([\d.]+)').Groups[1].Value
            $ns  = [regex]::Match($stut, '^\[perf\] w\d: (\d+) stutter').Groups[1].Value
            $top = ([regex]::Matches(($phase -replace '^.*avg \(p95\) - ', ''), '([a-z-]+) ([\d.]+)\(([\d.]+)\)') | Select-Object -First 4 |
                    ForEach-Object { "$($_.Groups[1].Value) $($_.Groups[2].Value)($($_.Groups[3].Value))" }) -join ', '
            $cause = [regex]::Match($worst, '<- (.*)$').Groups[1].Value
            $rows += "| $name | w$w | $($avg[1].Value) ms ($($avg[2].Value) fps) | $p99 / $max | $ns | $top | $cause |"
        }
    }
}

$md = @('| run | window | avg | p99 / max ms | stutter frames | biggest phases ms avg(p95) | worst frame cause |',
        '|---|---|---|---|---|---|---|') + $rows
Set-Content -Path "$out\summary.md" -Value $md -Encoding utf8
$md
"== summary: $out\summary.md"
